<script>
import {installPrintPageFooter} from 'src/utils/printPageFooter'

const PERSIAN = '۰۱۲۳۴۵۶۷۸۹'

/**
 * متن کامل قرارداد (مطابق نمونه قرارداد خورشید یار یزد) که با داده قرارداد پر می‌شود.
 * data همان ساختاری است که بک‌اند در AutomationContract::buildData / snapshot برمی‌گرداند.
 * در پیش‌نمایش کارتابل، fields می‌تواند مقادیر در حال ویرایش را جایگزین کند.
 */
export default {
  name: 'ContractDocument',
  props: {
    data: {type: Object, required: true},
    fields: {type: Object, default: null},
    signature: {type: String, default: ''},
    signerName: {type: String, default: ''},
    signedAt: {type: String, default: ''},
    signaturePlaceholder: {type: String, default: 'محل امضا'},
  },
  data() {
    return {
      contractor: 'شرکت خورشید یار یزد / آقای حمیدرضا رضانژاد فهادان به کد ملی ۴۴۲۰۲۲۳۱۳۸',
      contractorSigner: 'حمیدرضا رضانژاد فهادان',
    }
  },
  computed: {
    f() {
      return this.fields || this.data.fields || {}
    },
    employer() {
      return this.data.employer || {}
    },
    techItems() {
      return (this.f.tech_items || []).filter(i => i && (i.title || i.product_id))
    },
    items() {
      return this.data.items || []
    },
    cheques() {
      return this.data.cheques || []
    },
    payments() {
      return this.data.payments || []
    },
    chequeBanks() {
      return [...new Set(this.cheques.map(c => c.bank).filter(Boolean))].join('، ')
    },
  },
  methods: {
    num(value) {
      if (value === null || value === undefined || value === '') return ''
      return String(value).replace(/\d/g, d => PERSIAN[d])
    },
    // مقدار خالی به‌صورت نقطه‌چین (مثل نسخه چاپی) نمایش داده می‌شود
    v(value) {
      if (value === null || value === undefined || value === '') return '..........'
      return this.num(value)
    },
    money(value) {
      if (value === null || value === undefined || value === '') return '..........'
      return this.num(Math.round(Number(value)).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ','))
    },
  },
  // در چاپ قرارداد به جای هدر/فوتر مرورگر (نام نرم‌افزار و لینک صفحه) فقط شماره صفحه و تاریخ و ساعت چاپ می‌آید
  mounted() {
    this.removePrintFooter = installPrintPageFooter()
  },
  beforeUnmount() {
    if (this.removePrintFooter) this.removePrintFooter()
  }
}
</script>

